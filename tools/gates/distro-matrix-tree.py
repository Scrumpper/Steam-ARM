#!/usr/bin/env python3
"""Whole-tree snapshot and diff for distro-matrix.sh. Internal test tooling, never shipped.

distro-matrix-tree.py snap ROOT OUT
  every path under ROOT except /proc /sys /dev /run /tmp /sim: type, mode, owner, size, sha256 or link target
distro-matrix-tree.py diff BEFORE AFTER [--strict] [--purge] [--removal PY] [--home H] [--armhome A]
                          [--keep REGEX=REASON ...] [--keep-list FILE] [--count]
  differences; allowed ones carry a keep reason (check-removal.py KEEP with home and client folder filled in, plus
  --keep, plus paths in --keep-list); --strict allows none; --purge drops keeps that cover the RootFS or client
  folder (purge deletes them). Exit 1 on any difference without a reason."""
import hashlib
import importlib.util
import os
import re
import stat
import sys

SKIP_TOP = ("proc", "sys", "dev", "run", "tmp", "sim")
RFS = "/opt/fex-rootfs/Ubuntu_24_04"
# setup restores these byte for byte: no keep reason applies
EXACT = (r"^/etc/fstab$", r"^/boot/")
EXTRA = [
    (r"^/etc/ld\.so\.cache$", "regenerated by ldconfig"),
    (r"^/var/lib/apt/|^/var/cache/apt/|^/var/cache/debconf/|^/var/lib/dpkg/|^/var/log/|^/var/cache/ldconfig/",
     "package manager state and logs"),
]


def h(p):
    d = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            d.update(b)
    return d.hexdigest()


def snap(root, out):
    root = os.path.realpath(root)
    with open(out, "w") as o:
        for d, dirs, files in os.walk(root):
            rel = d[len(root):] or "/"
            if rel == "/":
                dirs[:] = [x for x in dirs if x not in SKIP_TOP]
                files = [x for x in files if x not in SKIP_TOP]
            for n in sorted(dirs) + sorted(files):
                p = os.path.join(d, n)
                st = os.lstat(p)
                m = st.st_mode
                if stat.S_ISLNK(m):
                    t, data = "l", os.readlink(p)
                elif stat.S_ISDIR(m):
                    t, data = "d", ""
                elif stat.S_ISREG(m):
                    t, data = "f", "%d:%s" % (st.st_size, h(p))
                else:
                    t, data = "o", ""
                path = (rel.rstrip("/") + "/" + n)
                o.write("%s\t%s\t%o\t%d\t%d\t%s\n" % (path.replace("\t", " ").replace("\n", " "), t,
                                                     stat.S_IMODE(m), st.st_uid, st.st_gid, data))
            # links to folders are entries, not walked
            dirs[:] = [x for x in dirs if not os.path.islink(os.path.join(d, x))]


def load(f):
    r = {}
    with open(f) as fh:
        for ln in fh:
            p, rest = ln.rstrip("\n").split("\t", 1)
            r[p] = rest
    return r


def removal_keeps(py, home, armhome):
    spec = importlib.util.spec_from_file_location("check_removal", py)
    m = importlib.util.module_from_spec(spec)
    sys.path.insert(0, os.path.dirname(os.path.realpath(py)))
    spec.loader.exec_module(m)
    out = []
    for rx, why in m.KEEP:
        rx = re.sub(r"\\\$\((?:UHOME|REALHOME|uh|HOME)[^)]*\)", lambda _: re.escape(home), rx)
        rx = re.sub(r"\\\$\((?:ARMHOME|armhome)[^)]*\)\\b", lambda _: re.escape(armhome), rx)
        out.append((rx, why))
    return out


def main(a):
    if len(a) == 3 and a[0] == "snap":
        snap(a[1], a[2])
        return 0
    if len(a) < 3 or a[0] != "diff":
        sys.exit(__doc__)
    before, after = load(a[1]), load(a[2])
    opts = a[3:]
    strict = "--strict" in opts
    purge = "--purge" in opts
    count = "--count" in opts
    home, armhome, py, keeps, listed = "/home/gamer", None, None, [], {}
    i = 0
    while i < len(opts):
        o = opts[i]
        if o in ("--home", "--armhome", "--removal", "--keep", "--keep-list"):
            v = opts[i + 1]
            i += 1
            if o == "--home":
                home = v
            elif o == "--armhome":
                armhome = v
            elif o == "--removal":
                py = v
            elif o == "--keep":
                rx, why = v.split("=", 1)
                keeps.append((rx, why))
            else:
                with open(v) as fh:
                    for ln in fh:
                        if "\t" in ln:
                            p, why = ln.rstrip("\n").split("\t", 1)
                            listed[p] = why
        i += 1
    armhome = armhome or home + "/.local/share/steam-arm"
    rules = []
    if not strict:
        rules = (removal_keeps(py, home, armhome) if py else []) + EXTRA + keeps
        if purge:
            rules = [(rx, w) for rx, w in rules
                     if not re.search(rx, RFS + "/x") and not re.search(rx, armhome + "/x")]
    rows, bad = [], 0
    for p in sorted(set(before) | set(after)):
        b, c = before.get(p), after.get(p)
        if b == c:
            continue
        kind = "added" if b is None else "removed" if c is None else "changed"
        why = None
        if not strict and not any(re.search(rx, p) for rx in EXACT):
            why = listed.get(p) or next((w for rx, w in rules if re.search(rx, p)), None)
        if why is None:
            bad += 1
        rows.append("%-7s %s%s" % (kind, p, "  [kept: %s]" % why if why else ""))
    if count:
        print("%d differences, %d without keep reason" % (len(rows), bad))
    for r in rows:
        if "[kept:" not in r or "-v" in opts:
            print(r)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
